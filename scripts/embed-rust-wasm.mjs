import { createHash } from 'node:crypto'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname } from 'node:path'

const [inputPath, outputPath] = process.argv.slice(2)
if (!inputPath || !outputPath) throw new Error('Usage: node scripts/embed-rust-wasm.mjs <input.wasm> <output.js>')

const bytes = await readFile(inputPath)
const base64 = bytes.toString('base64')
const sha256 = createHash('sha256').update(bytes).digest('hex')
const output = `// Generated by scripts/embed-rust-wasm.mjs. Do not edit.\nexport const RUST_SHA256_WASM_BASE64 = '${base64}'\nexport const RUST_SHA256_WASM_SHA256 = '${sha256}'\n`
await mkdir(dirname(outputPath), { recursive: true })
await writeFile(outputPath, output)
console.log(`Embedded ${bytes.length} WASM bytes (${sha256})`)
